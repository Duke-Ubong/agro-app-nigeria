/**
 * Quality Grading Engine for grain inspection:
 * Standard moisture benchmark:
 * <= 13.0% : Grade A (Premium export/industrial)
 * 13.1% - 14.5% : Grade B (Standard commercial)
 * > 14.5% : Grade C (High moisture - requires drying or feed discount)
 */
export function calculateGrainQualityGrade(moisture: number, foreignMatter: number): {
  grade: GrainGrade;
  basePriceNairaPerMT: number;
  qualityModifierPercent: number;
  recommendation: string;
} {
  if (moisture <= 13.0 && foreignMatter <= 1.5) {
    return {
      grade: 'Grade A (Export/Industrial)',
      basePriceNairaPerMT: 480000,
      qualityModifierPercent: 0,
      recommendation: 'Safe for long-term silo storage. Qualifies for premium brewery and food processing off-takers.',
    };
  } else if (moisture <= 14.5 && foreignMatter <= 2.5) {
    return {
      grade: 'Grade B (Standard Commercial)',
      basePriceNairaPerMT: 460000,
      qualityModifierPercent: -4.2,
      recommendation: 'Commercial standard. Move to ventilated flatbed storage; dispatch within 45 days.',
    };
  } else {
    return {
      grade: 'Grade C (Feed/Discounted)',
      basePriceNairaPerMT: 430000,
      qualityModifierPercent: -10.4,
      recommendation: 'Excess moisture detected. Immediate drying floor routing required before silo transfer to avoid aflatoxin mold.',
    };
  }
}
